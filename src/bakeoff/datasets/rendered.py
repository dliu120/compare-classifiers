"""Rendered image Cases with Gold by construction: receipts, dialog screenshots, color cards.

Every image is drawn with Pillow from values a seeded RNG chose, so the reference Answers are
known exactly. Images are canonicalized and stored under ``<family_dir>/images/<sha256>.png``.
"""

from __future__ import annotations

import random
from collections.abc import Callable
from dataclasses import dataclass, field
from datetime import date
from pathlib import Path
from typing import Any

from PIL import Image, ImageDraw, ImageFont

from bakeoff.datasets.case import Case, Reference
from bakeoff.datasets.family import FamilyManifest
from bakeoff.datasets.images import canonicalize, encode_png, write_image
from bakeoff.datasets.tokens import count_tokens
from bakeoff.systemone import ChoiceQuestion, Json, NoulQuestion, Question

FAMILY = "rendered-images"
KINDS = ("receipt", "ui", "color")

WHITE = (255, 255, 255)
BLACK = (20, 20, 20)
INK = (31, 41, 55)
PAGE = (243, 244, 246)
BORDER = (156, 163, 175)
ACCENT = (37, 99, 235)

STORES = [
    "Harbor Market",
    "Blue Fern Cafe",
    "Northgate Hardware",
    "Summit Outfitters",
    "Maple & Main Books",
    "Riverside Pharmacy",
]
ITEMS = [
    "Coffee beans 1kg",
    "Garden hose 25m",
    "Wool blanket",
    "Desk lamp",
    "Notebook set",
    "Olive oil 1L",
    "Trail boots",
    "Bluetooth speaker",
    "Cordless drill",
    "Rain jacket",
    "Ceramic mug",
    "Camping stove",
    "Printer paper",
    "Bike helmet",
    "Chef's knife",
]
CURRENCIES: dict[str, int] = {"USD": 2, "EUR": 2, "GBP": 2, "JPY": 0}  # code -> decimals
CURRENCY_NAMES: dict[str, Json | None] = {
    "USD": "US dollar",
    "EUR": "euro",
    "GBP": "pound sterling",
    "JPY": "Japanese yen",
}
THRESHOLD = 1000
AMBIGUITY_BAND = (900, 1100)  # totals in here are rejected so Gold is never a close call

BUTTONS = [
    "Save",
    "Cancel",
    "Delete",
    "Submit",
    "Back",
    "Next",
    "Export",
    "Share",
    "Retry",
    "Close",
    "Apply",
    "Discard",
]
TITLES = [
    "Export report",
    "Delete project?",
    "Settings",
    "Unsaved changes",
    "Invite teammates",
    "Confirm payment",
    "Rename folder",
]
BODIES = [
    "Choose an action to continue.",
    "This cannot be undone.",
    "Your changes will be applied to all members.",
    "Review the details before you proceed.",
]

PALETTE: dict[str, tuple[int, int, int]] = {
    "red": (220, 38, 38),
    "green": (22, 163, 74),
    "blue": (37, 99, 235),
    "yellow": (250, 204, 21),
    "orange": (249, 115, 22),
    "purple": (147, 51, 234),
    "black": (17, 17, 17),
    "white": (255, 255, 255),
    "gray": (128, 128, 128),
}


@dataclass
class Rendered:
    image: Image.Image
    state: str
    questions: dict[str, Question]
    reference: dict[str, Reference]
    meta: dict[str, Any] = field(default_factory=dict)


Renderer = Callable[[random.Random, int], Rendered]


def build_rendered_cases(
    family_dir: Path, *, count: int = 40, seed: int = 0, family: str = FAMILY
) -> list[Case]:
    """Draw ``count`` images, cycling through the kinds, into ``<family_dir>/images``."""
    rng = random.Random(seed)
    cases = []
    for index in range(count):
        kind = KINDS[index % len(KINDS)]
        rendered = RENDERERS[kind](rng, index // len(KINDS))
        data, sha256 = canonicalize(encode_png(rendered.image))
        relative = write_image(family_dir, data, sha256)
        cases.append(
            Case(
                id=f"{family}-{index:03d}",
                family=family,
                track="image",
                state=rendered.state,
                image_path=relative,
                image_sha256=sha256,
                questions=rendered.questions,
                reference=rendered.reference,
                meta={"kind": kind, **rendered.meta},
                approx_tokens=count_tokens(rendered.state),
            )
        )
    return cases


def manifest(created: date, *, seed: int = 0, family: str = FAMILY) -> FamilyManifest:
    return FamilyManifest(
        name=family,
        track="image",
        source=f"bakeoff.datasets.rendered (Pillow, seed {seed})",
        license="synthetic; generated by this project, no third-party content",
        reference_kind="gold",
        generated_by="bakeoff.datasets.rendered.build_rendered_cases",
        created=created,
        notes="Kinds cycle receipt, ui, color. Receipt totals never fall within 900..1100.",
    )


def render_receipt(rng: random.Random, variant: int) -> Rendered:
    above = variant % 2 == 0
    code = rng.choice(sorted(CURRENCIES))
    decimals = CURRENCIES[code]
    prices, subtotal, tax, total = _amounts(rng, above, decimals)
    names = rng.sample(ITEMS, len(prices))
    image = Image.new("RGB", (480, 640), WHITE)
    draw = ImageDraw.Draw(image)
    big, normal = _font(30), _font(22)
    y = 30
    _center(draw, rng.choice(STORES), y, big, image.width)
    y += 50
    _center(draw, f"{_date(rng)}   Receipt #{rng.randint(1000, 99999)}", y, normal, image.width)
    y += 40
    draw.line((30, y, 450, y), fill=BLACK, width=2)
    y += 20
    for name, price in zip(names, prices, strict=True):
        _row(draw, name, _money(price, decimals), y, normal)
        y += 32
    y += 8
    draw.line((30, y, 450, y), fill=BLACK, width=2)
    y += 20
    _row(draw, "Subtotal", _money(subtotal, decimals), y, normal)
    y += 32
    _row(draw, "Tax", _money(tax, decimals), y, normal)
    y += 44
    _row(draw, "TOTAL", f"{code} {_money(total, decimals)}", y, big)
    y += 60
    _center(draw, "Thank you for shopping with us", y, normal, image.width)
    return Rendered(
        image=image,
        state="The attached image is a store receipt. Read the printed total and its currency.",
        questions={
            "above_1000": NoulQuestion(
                instructions=(
                    "Is the total printed on this receipt above 1000, in the receipt's own "
                    "currency?"
                )
            ),
            "currency": ChoiceQuestion(
                instructions="Which currency is the receipt's total in?",
                criteria=dict(CURRENCY_NAMES),
            ),
        },
        reference={
            "above_1000": Reference(kind="gold", noul=total > THRESHOLD, source="by construction"),
            "currency": Reference(kind="gold", choice=code, source="by construction"),
        },
        meta={"total": total, "currency": code, "items": len(prices)},
    )


def render_ui(rng: random.Random, variant: int) -> Rendered:
    labels = rng.sample(BUTTONS, 3 + variant % 3)
    highlighted = rng.choice(labels)
    image = Image.new("RGB", (640, 400), PAGE)
    draw = ImageDraw.Draw(image)
    draw.rectangle((40, 40, 600, 360), fill=WHITE, outline=BORDER, width=2)
    draw.text((64, 64), rng.choice(TITLES), fill=INK, font=_font(26))
    draw.text((64, 120), rng.choice(BODIES), fill=INK, font=_font(20))
    width, height, gap = 110, 44, 14
    x = 600 - 24 - width
    font = _font(20)
    for label in reversed(labels):
        box = (x, 360 - 24 - height, x + width, 360 - 24)
        if label == highlighted:
            draw.rectangle(box, fill=ACCENT)
            color = WHITE
        else:
            draw.rectangle(box, fill=WHITE, outline=BORDER, width=2)
            color = INK
        text_width = draw.textlength(label, font=font)
        draw.text((x + (width - text_width) / 2, box[1] + 10), label, fill=color, font=font)
        x -= width + gap
    return Rendered(
        image=image,
        state=(
            "The attached image is a screenshot of a dialog. Exactly one button is highlighted: "
            "filled with the accent color."
        ),
        questions={
            "highlighted": ChoiceQuestion(
                instructions="Which button is highlighted?", criteria=dict.fromkeys(labels)
            )
        },
        reference={
            "highlighted": Reference(kind="gold", choice=highlighted, source="by construction")
        },
        meta={"buttons": labels, "highlighted": highlighted},
    )


def render_color_card(rng: random.Random, variant: int) -> Rendered:
    dominant = rng.choice(sorted(PALETTE))
    two_tone = variant % 2 == 1
    image = Image.new("RGB", (320, 240), PALETTE[dominant])
    draw = ImageDraw.Draw(image)
    secondary = None
    if two_tone:
        secondary = rng.choice([name for name in sorted(PALETTE) if name != dominant])
        if rng.random() < 0.5:
            draw.rectangle((240, 0, 319, 239), fill=PALETTE[secondary])
        else:
            draw.rectangle((0, 180, 319, 239), fill=PALETTE[secondary])
    draw.rectangle((0, 0, 319, 239), outline=(60, 60, 60), width=3)
    return Rendered(
        image=image,
        state="The attached image is a color card. Name the color that covers most of it.",
        questions={
            "color": ChoiceQuestion(
                instructions="Which color covers most of the card?", criteria=dict.fromkeys(PALETTE)
            )
        },
        reference={"color": Reference(kind="gold", choice=dominant, source="by construction")},
        meta={"dominant": dominant, "secondary": secondary},
    )


RENDERERS: dict[str, Renderer] = {
    "receipt": render_receipt,
    "ui": render_ui,
    "color": render_color_card,
}


def _amounts(
    rng: random.Random, above: bool, decimals: int
) -> tuple[list[float], float, float, float]:
    """Item prices whose total lands clearly above or below the threshold."""
    low, high = (150, 2500) if above else (3, 300)
    while True:
        prices = [round(rng.uniform(low, high), decimals) for _ in range(rng.randint(2, 6))]
        subtotal = round(sum(prices), decimals)
        tax = round(subtotal * rng.choice((0.0, 0.05, 0.08, 0.2)), decimals)
        total = round(subtotal + tax, decimals)
        if AMBIGUITY_BAND[0] <= total <= AMBIGUITY_BAND[1]:
            continue
        if (total > THRESHOLD) == above:
            return prices, subtotal, tax, total


def _money(value: float, decimals: int) -> str:
    return f"{value:,.{decimals}f}"


def _date(rng: random.Random) -> str:
    return f"2026-{rng.randint(1, 12):02d}-{rng.randint(1, 28):02d}"


def _font(size: int) -> ImageFont.ImageFont | ImageFont.FreeTypeFont:
    try:
        return ImageFont.load_default(size=size)
    except TypeError:  # Pillow without FreeType: a bitmap font of one fixed size
        return ImageFont.load_default()


def _center(draw: ImageDraw.ImageDraw, text: str, y: int, font: Any, width: int) -> None:
    draw.text(((width - draw.textlength(text, font=font)) / 2, y), text, fill=BLACK, font=font)


def _row(draw: ImageDraw.ImageDraw, left: str, right: str, y: int, font: Any) -> None:
    draw.text((40, y), left, fill=BLACK, font=font)
    draw.text((440 - draw.textlength(right, font=font), y), right, fill=BLACK, font=font)
